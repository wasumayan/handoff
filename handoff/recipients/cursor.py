from pathlib import Path

from .base import Recipient

FRONTMATTER = """---
description: Handoff from a previous coding agent session (generated by handoff)
alwaysApply: true
---
"""


class CursorRecipient(Recipient):
    name = "cursor"

    def install_path(self, cwd: str) -> Path:
        return Path(cwd) / ".cursor" / "rules" / "handoff.mdc"

    def install(self, cwd: str, files: dict[str, str]) -> Path:
        # .mdc is a whole-file rule; we own this file, so overwrite rather than splice.
        path = self.install_path(cwd)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(FRONTMATTER + files["HANDOFF.md"])
        return path
